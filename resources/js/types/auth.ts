export type User = {
    id: number;
    name: string;
    email: string;
    avatar?: string;
    email_verified_at: string | null;
    two_factor_enabled?: boolean;
    created_at: string;
    updated_at: string;
    [key: string]: unknown;
};

export type Auth = {
    user: User;
    permissions: string[];
    globalAccess: boolean;
    abilities: Abilities;
};

export type Abilities = {
    manageConnections: boolean;
    viewOrderReferences: boolean;
    viewSourceReferences: boolean;
    viewSchedules: boolean;
};

export type TwoFactorSetupData = {
    svg: string;
    url: string;
};

export type TwoFactorSecretKey = {
    secretKey: string;
};
